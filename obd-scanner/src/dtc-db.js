export function describeDtc(code) {
  const c = code.toUpperCase();
  const system = SYSTEMS[c[0]] || 'غير معروف';
  // SAE J2012: x0xxx generic; P2xxx and P34xx-P39xx generic; the rest are manufacturer-defined.
  const generic = c[1] === '0' || (c[0] === 'P' && (c[1] === '2' || (c[1] === '3' && c[2] >= '4')));
  const known = D[c];
  let title = known;
  if (!title) {
    const group = c[0] === 'P' ? P_GROUPS[c[2]] : null;
    title = group ? `عطل في ${group}` : `عطل في ${system}`;
  }
  return {
    code: c,
    title,
    system,
    generic,
    manufacturerSpecific: !generic,
    known: Boolean(known),
    guide: G[c] || null,
  };
}
